class TestConvertPqrToPdb:
    """Test PQR to PDB conversion with mocked MDAnalysis."""

    def test_convert_calls_mdanalysis(self):
        """Verify that convert_pqr_to_pdb calls MDAnalysis correctly."""
        mock_universe = MagicMock()
        mock_atom = MagicMock()
        mock_segment = MagicMock()
        mock_atom.segment = mock_segment

        # atoms needs to be iterable AND have a .write() method
        mock_atoms = MagicMock()
        mock_atoms.__iter__ = MagicMock(return_value=iter([mock_atom]))
        mock_universe.atoms = mock_atoms

        # Mock the top-level mda.Universe in core module
        with patch("core.mda.Universe", return_value=mock_universe):
            convert_pqr_to_pdb("/tmp/test.pqr", "/tmp/test.pdb")

            # segid should be cleared
            assert mock_segment.segid == ""
            # write should have been called
            mock_atoms.write.assert_called_once_with("/tmp/test.pdb")
