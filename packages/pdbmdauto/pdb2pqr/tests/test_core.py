class TestRunPdb2pqr:
    """Test subprocess execution."""

    @patch("core.subprocess.run")
    def test_successful_run(self, mock_run):
        mock_result = MagicMock()
        mock_result.stdout = "Success: PQR file created\n"
        mock_result.returncode = 0
        mock_run.return_value = mock_result

        stdout, returncode = run_pdb2pqr(["pdb2pqr", "in.pdb", "out.pqr"], "/tmp")

        assert returncode == 0
        assert "Success" in stdout
        mock_run.assert_called_once()

    @patch("core.subprocess.run")
    def test_failed_run(self, mock_run):
        mock_result = MagicMock()
        mock_result.stdout = "Error: Invalid PDB file\n"
        mock_result.returncode = 1
        mock_run.return_value = mock_result

        stdout, returncode = run_pdb2pqr(["pdb2pqr", "bad.pdb", "out.pqr"], "/tmp")

        assert returncode == 1
        assert "Error" in stdout

    @patch("core.subprocess.run")
    def test_working_directory_passed(self, mock_run):
        mock_result = MagicMock()
        mock_result.stdout = ""
        mock_result.returncode = 0
        mock_run.return_value = mock_result

        run_pdb2pqr(["pdb2pqr", "in.pdb", "out.pqr"], "/my/workdir")

        _, kwargs = mock_run.call_args
        assert kwargs["cwd"] == "/my/workdir"

    @patch("core.subprocess.run")
    def test_empty_stdout(self, mock_run):
        mock_result = MagicMock()
        mock_result.stdout = None
        mock_result.returncode = 0
        mock_run.return_value = mock_result

        stdout, returncode = run_pdb2pqr(["pdb2pqr"], "/tmp")

        assert stdout == ""
        assert returncode == 0


