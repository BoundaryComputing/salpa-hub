class TestFindExecutable:
    """Test pdb2pqr executable discovery."""

    def test_custom_path_exists(self, output_dir):
        # Create a fake pdb2pqr binary
        fake_bin = os.path.join(output_dir, "pdb2pqr")
        with open(fake_bin, "w") as f:
            f.write("#!/bin/sh\n")
        result = find_pdb2pqr_executable(fake_bin)
        assert result == fake_bin

    def test_custom_path_not_found(self):
        with pytest.raises(FileNotFoundError, match="Custom pdb2pqr path not found"):
            find_pdb2pqr_executable("/nonexistent/pdb2pqr")

    @patch("core.os.path.exists")
    @patch("core.sys.executable", "/fake/python/bin/python")
    def test_auto_detect_from_python_env(self, mock_exists):
        """Should find pdb2pqr next to sys.executable."""
        mock_exists.side_effect = lambda p: p == "/fake/python/bin/pdb2pqr"
        result = find_pdb2pqr_executable()
        assert result == "/fake/python/bin/pdb2pqr"

    @patch("core.os.path.exists", return_value=False)
    @patch("core.sys.executable", "/fake/python/bin/python")
    def test_fallback_to_path(self, mock_exists):
        """Should return bare 'pdb2pqr' when not found in python env."""
        result = find_pdb2pqr_executable()
        assert result == "pdb2pqr"

    @patch("core.os.name", "nt")
    @patch("core.os.path.exists", return_value=False)
    @patch("core.sys.executable", "C:\\Python\\python.exe")
    def test_windows_fallback(self, mock_exists):
        """On Windows, should fallback to pdb2pqr.exe."""
        result = find_pdb2pqr_executable()
        assert result == "pdb2pqr.exe"


